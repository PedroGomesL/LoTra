class MorphologyEngine:
    """
    Motor morfológico de alta precisão para tradução offline Inglês -> Português.
    Aplica regras léxico-gramaticais para:
    1. Plurais em inglês (-s, -es, -ies) mapeados para plurais em português.
    2. Formas verbais (-ing -> gerúndio/substantivo, -ed -> particípio, -s/-es -> 3ª pessoa).
    3. Advérbios em -ly mapeados para -mente.
    4. Sufixos cognatos clássicos (-tion -> -ção, -ity -> -idade, -ment -> -mento, etc.).
    5. Formas possessivas ('s e ') e contrações inglesas (don't, it's, etc.).
    """

    POSSESSIVES: Dict[str, str] = {
        "users'": "dos usuários",
        "users's": "dos usuários",
        "user's": "do usuário",
        "students'": "dos estudantes",
        "student's": "do estudante",
        "children's": "das crianças",
        "child's": "da criança",
        "people's": "das pessoas",
        "author's": "do autor",
        "authors'": "dos autores",
        "agent's": "do agente",
        "agents'": "dos agentes",
        "bloom's": "de Bloom",
        "sweller's": "de Sweller",
        "jonassen's": "de Jonassen",
        "wood et al.'s": "de Wood et al.",
        "jones et al.'s": "de Jones et al.",
        "hayles'": "de Hayles",
        "it's": "é",
        "that's": "isso é",
        "there's": "há",
        "what's": "o que é",
        "don't": "não",
        "doesn't": "não",
        "didn't": "não",
        "can't": "não pode",
        "cannot": "não pode",
        "couldn't": "não pôde",
        "won't": "não irá",
    }

    @staticmethod
    def pluralize_pt(pt_word: str) -> str:
        if not pt_word:
            return ""
        if " " in pt_word or pt_word.endswith("s"):
            return pt_word
        if pt_word.endswith(("a", "e", "i", "o", "u", "á", "é", "ó")):
            return pt_word + "s"
        if pt_word.endswith("ão"):
            return pt_word[:-2] + "ões"
        if pt_word.endswith(("r", "z")):
            return pt_word + "es"
        if pt_word.endswith("m"):
            return pt_word[:-1] + "ns"
        if pt_word.endswith("al"):
            return pt_word[:-2] + "ais"
        if pt_word.endswith("el"):
            return pt_word[:-2] + "eis"
        if pt_word.endswith("il"):
            return pt_word[:-2] + "is"
        if pt_word.endswith("ol"):
            return pt_word[:-2] + "ois"
        if pt_word.endswith("ul"):
            return pt_word[:-2] + "uis"
        return pt_word + "s"

    @staticmethod
    def verb_to_gerund_pt(pt_verb: str) -> Optional[str]:
        if pt_verb.endswith("ar"):
            return pt_verb[:-2] + "ando"
        if pt_verb.endswith("er"):
            return pt_verb[:-2] + "endo"
        if pt_verb.endswith("ir"):
            return pt_verb[:-2] + "indo"
        return None

    @staticmethod
    def verb_to_participle_pt(pt_verb: str) -> Optional[str]:
        if pt_verb.endswith("ar"):
            return pt_verb[:-2] + "ado"
        if pt_verb.endswith(("er", "ir")):
            return pt_verb[:-2] + "ido"
        return None

    @staticmethod
    def verb_to_3rd_person_pt(pt_verb: str) -> Optional[str]:
        if pt_verb.endswith("ar"):
            return pt_verb[:-2] + "a"
        if pt_verb.endswith(("er", "ir")):
            return pt_verb[:-2] + "e"
        return None

    @classmethod
    def translate_token(cls, tok: str, lexicon: Dict[str, str]) -> Optional[str]:
        clean_tok = tok.strip()
        if not clean_tok:
            return None

        lower = clean_tok.lower()

        # 1. Correspondência exata direta no dicionário
        if lower in lexicon:
            return lexicon[lower]

        # 2. Possessivos e contrações
        if lower in cls.POSSESSIVES:
            return cls.POSSESSIVES[lower]

        # 3. Sufixos de possessivo geral (ex: Anderson's -> de Anderson)
        if lower.endswith("'s") and len(lower) > 2:
            base = lower[:-2]
            if base in lexicon:
                return f"de {lexicon[base]}"
            return f"de {clean_tok[:-2]}"
        if lower.endswith("'") and len(lower) > 2:
            base = lower[:-1]
            if base in lexicon:
                return f"dos {cls.pluralize_pt(lexicon[base])}"

        # 4. Formas plurais em inglês (-ies, -es, -s)
        if lower.endswith("ies") and len(lower) > 4:
            sing = lower[:-3] + "y"
            if sing in lexicon:
                return cls.pluralize_pt(lexicon[sing])
        elif lower.endswith("es") and len(lower) > 3:
            sing = lower[:-2]
            if sing in lexicon:
                return cls.pluralize_pt(lexicon[sing])
            sing_e = lower[:-1]
            if sing_e in lexicon:
                return cls.pluralize_pt(lexicon[sing_e])
        elif lower.endswith("s") and not lower.endswith("ss") and len(lower) > 2:
            sing = lower[:-1]
            if sing in lexicon:
                return cls.pluralize_pt(lexicon[sing])

        # 5. Formas verbais em -ing (gerúndio / particípio presente / substantivo)
        if lower.endswith("ing") and len(lower) > 4:
            stem = lower[:-3]
            if stem in lexicon:
                pt_base = lexicon[stem]
                ger = cls.verb_to_gerund_pt(pt_base)
                if ger:
                    return ger
            stem_e = stem + "e"
            if stem_e in lexicon:
                pt_base = lexicon[stem_e]
                ger = cls.verb_to_gerund_pt(pt_base)
                if ger:
                    return ger
            if len(stem) > 2 and stem[-1] == stem[-2]:
                stem_dup = stem[:-1]
                if stem_dup in lexicon:
                    ger = cls.verb_to_gerund_pt(lexicon[stem_dup])
                    if ger:
                        return ger

        # 6. Formas verbais em -ed (passado / particípio)
        if lower.endswith("ed") and len(lower) > 3:
            stem = lower[:-2]
            if stem in lexicon:
                pt_base = lexicon[stem]
                part = cls.verb_to_participle_pt(pt_base)
                if part:
                    return part
            stem_d = lower[:-1]
            if stem_d in lexicon:
                pt_base = lexicon[stem_d]
                part = cls.verb_to_participle_pt(pt_base)
                if part:
                    return part

        # 7. Formas de 3ª pessoa do singular em verbos (-s, -es)
        if lower.endswith("s") and len(lower) > 3:
            stem = lower[:-1]
            if stem in lexicon and lexicon[stem].endswith(("ar", "er", "ir")):
                p3 = cls.verb_to_3rd_person_pt(lexicon[stem])
                if p3:
                    return p3

        # 8. Advérbios em -ly derivando de adjetivos
        if lower.endswith("ly") and len(lower) > 4:
            stem = lower[:-2]
            if stem.endswith("i"):
                stem_adj = stem[:-1] + "y"
                if stem_adj in lexicon:
                    stem = stem_adj
            if stem in lexicon:
                pt_adj = lexicon[stem]
                accent_map = {'á': 'a', 'é': 'e', 'í': 'i', 'ó': 'o', 'ú': 'u', 'â': 'a', 'ê': 'e', 'ô': 'o'}
                clean_adj = "".join(accent_map.get(c, c) for c in pt_adj)
                if clean_adj.endswith("o"):
                    return clean_adj[:-1] + "amente"
                elif clean_adj.endswith("a"):
                    return clean_adj + "mente"
                elif clean_adj.endswith("e") or clean_adj.endswith(("l", "r", "s", "m")):
                    return clean_adj + "mente"

        # 9. Sufixos cognatos universais inglês -> português
        if lower.endswith("tions"):
            base = lower[:-5]
            if base in lexicon:
                return lexicon[base] + "ções"
            return lower[:-5] + "ções"
        if lower.endswith("tion"):
            return lower[:-4] + "ção"
        if lower.endswith("sions"):
            return lower[:-5] + "sões"
        if lower.endswith("sion"):
            return lower[:-4] + "são"
        if lower.endswith("ities"):
            return lower[:-5] + "idades"
        if lower.endswith("ity"):
            return lower[:-3] + "idade"
        if lower.endswith("ments"):
            return lower[:-5] + "mentos"
        if lower.endswith("ment"):
            return lower[:-4] + "mento"
        if lower.endswith("ences"):
            return lower[:-5] + "ências"
        if lower.endswith("ence"):
            return lower[:-4] + "ência"
        if lower.endswith("ances"):
            return lower[:-5] + "âncias"
        if lower.endswith("ance"):
            return lower[:-4] + "ância"
        if lower.endswith("ables"):
            return lower[:-5] + "áveis"
        if lower.endswith("able"):
            return lower[:-4] + "ável"
        if lower.endswith("ibles"):
            return lower[:-5] + "íveis"
        if lower.endswith("ible"):
            return lower[:-4] + "ível"
        if lower.endswith("ologies"):
            return lower[:-7] + "ologias"
        if lower.endswith("ology"):
            return lower[:-5] + "ologia"
        if lower.endswith("isms"):
            return lower[:-4] + "ismos"
        if lower.endswith("ism"):
            return lower[:-3] + "ismo"
        if lower.endswith("ists"):
            return lower[:-4] + "istas"
        if lower.endswith("ist"):
            return lower[:-3] + "ista"

        # 10. Prefixos comuns (non-, un-, co-, sub-, inter-)
        if lower.startswith("non-") or lower.startswith("non"):
            prefix = "non-" if lower.startswith("non-") else "non"
            rest = lower[len(prefix):]
            if rest in lexicon:
                return f"não-{lexicon[rest]}"
        if lower.startswith("un-") or lower.startswith("un"):
            prefix = "un-" if lower.startswith("un-") else "un"
            rest = lower[len(prefix):]
            if rest in lexicon:
                return f"não-{lexicon[rest]}"

        return None
